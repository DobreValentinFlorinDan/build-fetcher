// npm run gpu:ptx: compiles server/gpu/similarities.cu and sums.cu to PTX with NVIDIA's runtime compiler (NVRTC) into
// server/gpu/kernel.ts. Only needed after changing the .cu file; the app ships the PTX, and the NVIDIA driver compiles
// it for the card it runs on. NVRTC comes with the CUDA toolkit, or as the nvidia-cuda-nvrtc-cu12 Python wheel:
//   NVRTC_LIB=/path/to/libnvrtc.so.12 npm run gpu:ptx        (nvrtc64_120_0.dll on Windows)
import fs from 'node:fs';
import koffi from 'koffi';

const lib = process.env.NVRTC_LIB;
if (!lib) { console.error('Set NVRTC_LIB to the NVRTC library (libnvrtc.so.12 or nvrtc64_120_0.dll).'); process.exit(1); }
const nvrtc = koffi.load(lib);
const version = nvrtc.func('int nvrtcVersion(_Out_ int *major, _Out_ int *minor)');
const create = nvrtc.func('int nvrtcCreateProgram(_Out_ void **prog, const char *src, const char *name, int numHeaders, void *headers, void *includeNames)');
const compile = nvrtc.func('int nvrtcCompileProgram(void *prog, int numOptions, const char **options)');
const logSize = nvrtc.func('int nvrtcGetProgramLogSize(void *prog, _Out_ size_t *size)');
const getLog = nvrtc.func('int nvrtcGetProgramLog(void *prog, void *log)');
const ptxSize = nvrtc.func('int nvrtcGetPTXSize(void *prog, _Out_ size_t *size)');
const getPtx = nvrtc.func('int nvrtcGetPTX(void *prog, void *ptx)');

// compute_52 (Maxwell, 2014) and later; nothing fused into a multiply-add unless the source asks for it.
const options = ['--gpu-architecture=compute_52', '--fmad=false', '-std=c++17'];
const major = [0], minor = [0];
version(major, minor);

function build(file: string): string {
  const prog: unknown[] = [null];
  if (create(prog, fs.readFileSync(`server/gpu/${file}`, 'utf8'), file, 0, null, null) !== 0) throw new Error(`nvrtcCreateProgram failed for ${file}`);
  const result = compile(prog[0], options.length, options);
  const size = [0];
  logSize(prog[0], size);
  const log = Buffer.alloc(Number(size[0]));
  getLog(prog[0], log);
  if (log.length > 1) console.log(log.toString('utf8', 0, log.length - 1));
  if (result !== 0) { console.error(`NVRTC failed on ${file} (${result})`); process.exit(1); }
  ptxSize(prog[0], size);
  const ptx = Buffer.alloc(Number(size[0]));
  getPtx(prog[0], ptx);
  return ptx.toString('utf8', 0, ptx.length - 1);
}

const similarities = build('similarities.cu'), sums = build('sums.cu');
fs.writeFileSync('server/gpu/kernel.ts', `// Generated by npm run gpu:ptx (scripts/build-ptx.ts) from similarities.cu and sums.cu with NVRTC ${major[0]}.${minor[0]} (${options.join(' ')}). Don't edit.
export const SIMILARITIES_PTX = ${JSON.stringify(similarities)};
export const SUMS_PTX = ${JSON.stringify(sums)};
`);
console.log(`server/gpu/kernel.ts: ${similarities.length} + ${sums.length} characters of PTX (NVRTC ${major[0]}.${minor[0]})`);
